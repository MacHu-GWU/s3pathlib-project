# -*- coding: utf-8 -*-

"""
Count the lines of the library, the tests and the hand-written docs.

Run with ``mise run count-code``; ``cloc`` is installed by ``mise install``.

**Design notes**

Python goes through cloc, docs do not
    cloc counts every line of ``.rst`` prose as a "comment" and mixes the
    markdown of a notebook with its code, so docs are counted here: non-blank
    lines of prose and of code, outputs left out.

Only hand-written docs
    ``docs/source/api/`` is generated by ``conf.py``, ``_static/`` is vendored
    and the ``.rst`` files of ``docs/source/`` only include the ones at the
    project root, so none of them is counted.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

dir_project_root = Path(__file__).absolute().parent.parent.parent
dir_docs_source = dir_project_root.joinpath("docs", "source")

# (group, directory), counted by cloc, Python only
PYTHON_GROUPS = [
    ("library", dir_project_root.joinpath("s3pathlib")),
    ("tests", dir_project_root.joinpath("tests")),
]


def find_notebooks() -> list[Path]:
    return sorted(dir_docs_source.glob("[0-9][0-9]-*/index.ipynb"))


def find_rst_files() -> list[Path]:
    # the .rst files under docs/source/ only include these two
    return [
        dir_project_root.joinpath("README.rst"),
        dir_project_root.joinpath("release-history.rst"),
    ]


def count_python(path: Path) -> dict[str, int]:
    """
    Return ``{"nFiles": ..., "code": ..., "comment": ..., "blank": ...}``.
    """
    args = ["cloc", "--json", "--quiet", "--include-lang=Python", str(path)]
    result = subprocess.run(args, capture_output=True, text=True, check=True)
    data = json.loads(result.stdout)
    return data["Python"]


def count_non_blank(lines: list[str]) -> int:
    n = 0
    for line in lines:
        if line.strip():
            n += 1
    return n


def count_notebooks(paths: list[Path]) -> tuple[int, int]:
    """
    Return the non-blank lines of (markdown cells, code cells).
    """
    prose = 0
    code = 0
    for path in paths:
        notebook = json.loads(path.read_text(encoding="utf-8"))
        for cell in notebook["cells"]:
            source = cell["source"]
            # nbformat allows the source as one string or a list of lines
            if isinstance(source, str):
                lines = source.splitlines()
            else:
                lines = "".join(source).splitlines()
            if cell["cell_type"] == "code":
                code += count_non_blank(lines)
            elif cell["cell_type"] == "markdown":
                prose += count_non_blank(lines)
    return prose, code


def count_rst(paths: list[Path]) -> int:
    total = 0
    for path in paths:
        lines = path.read_text(encoding="utf-8").splitlines()
        total += count_non_blank(lines)
    return total


def print_table(title: str, rows: list[list[str]]):
    """
    The first row is the header; the first column aligns left, the others right.
    """
    widths = []
    for i in range(len(rows[0])):
        widths.append(max(len(row[i]) for row in rows))
    width = sum(widths) + 2 * (len(widths) - 1)
    print(title)
    print("=" * width)
    for n, row in enumerate(rows):
        cells = []
        for i, cell in enumerate(row):
            if i == 0:
                cells.append(cell.ljust(widths[i]))
            else:
                cells.append(cell.rjust(widths[i]))
        print("  ".join(cells))
        if n == 0:
            print("-" * width)
    print()


def main():
    rows = [["Python", "Files", "Code", "Comment + docstring", "Blank"]]
    python_code = {}
    for group, path in PYTHON_GROUPS:
        data = count_python(path)
        python_code[group] = data["code"]
        label = f"{group} ({path.name}/)"
        rows.append(
            [
                label,
                f"{data['nFiles']:,}",
                f"{data['code']:,}",
                f"{data['comment']:,}",
                f"{data['blank']:,}",
            ]
        )
    print_table("Python (cloc)", rows)

    notebooks = find_notebooks()
    rst_files = find_rst_files()
    notebook_prose, notebook_code = count_notebooks(notebooks)
    rst_prose = count_rst(rst_files)
    rows = [
        ["Docs", "Files", "Prose", "Code"],
        [
            "notebooks (docs/source/NN-*/)",
            f"{len(notebooks):,}",
            f"{notebook_prose:,}",
            f"{notebook_code:,}",
        ],
        [
            "rst (README.rst, release-history.rst)",
            f"{len(rst_files):,}",
            f"{rst_prose:,}",
            "-",
        ],
    ]
    print_table("Docs (non-blank lines, outputs left out)", rows)

    ratio = python_code["tests"] / python_code["library"]
    print(f"Lines of test code per line of library code: {ratio:.2f}")


if __name__ == "__main__":
    main()
